#!/usr/bin/env node
// Writes docs/screenshots/CREDITS.md from tools/demo/library.json: every film, image and video the
// demo library uses, with its author, licence and source.
//
//   node tools/demo/credits.mjs > docs/screenshots/CREDITS.md
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const lib = JSON.parse(readFileSync(join(HERE, 'library.json'), 'utf8'));
const cell = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
// Commons author fields: drop doubled text ("Unknown authorUnknown author") and cap long crew lists
const who = (s) => {
  let t = String(s || '').replace(/\s+/g, ' ').trim().replace(/^(.+?)\1$/, '$1');
  if (t.length > 110) {
    const cut = t.slice(0, 110);
    const at = Math.max(cut.lastIndexOf(','), cut.lastIndexOf('/'), cut.lastIndexOf(';'));
    t = `${(at > 40 ? cut.slice(0, at) : cut).trim()} et al.`;
  }
  return cell(t);
};
const link = (text, url) => (url ? `[${cell(text)}](${url})` : cell(text));

// Which titles/people each media id is used for.
const uses = {};
const use = (id, what) => { if (id) (uses[id] = uses[id] || []).push(what); };
for (const m of lib.movies || []) {
  use(m.poster, `${m.title}: poster`);
  use(m.backdrop, `${m.title}: backdrop`);
  use(m.logo, `${m.title}: logo`);
  (m.extras || []).forEach((x) => use(x.thumb, `${m.title}: "${x.title}" thumbnail`));
}
for (const s of lib.shows || []) {
  use(s.poster, `${s.title}: poster`);
  use(s.backdrop, `${s.title}: backdrop`);
  use(s.logo, `${s.title}: logo`);
  (s.seasons || []).forEach((se) => (se.episodes || []).forEach((e) => use(e.thumb, `${s.title}: "${e.title}" thumbnail`)));
}
for (const c of lib.collections || []) use(c.poster, `${c.title}: collection poster`);
for (const [name, id] of Object.entries(lib.people || {})) use(id, `${name}: photo`);

const out = [];
out.push('# Screenshot credits', '');
out.push('The screenshots in this folder show Plex Lite playing a **demo library** served by',
  '[`tools/demo/server.mjs`](../../tools/demo/server.mjs), not anyone\'s real Plex library. Every film in',
  'it is either a Creative Commons open movie or in the public domain, and every image comes from',
  'Wikimedia Commons under a free licence (or is in the public domain). Titles without free artwork',
  'use typographic placeholders and wordmarks generated by [`tools/demo/art.mjs`](../../tools/demo/art.mjs).',
  'Cast members without a freely licensed photo show the app\'s initials fallback.', '');
out.push('**Licence of the screenshots.** The screenshots include the works below. Where those are',
  'CC BY-SA, the screenshots that show them are shared under the same licence',
  '([CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/)); otherwise they may be used',
  'under [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) with the attributions below. The app',
  'itself is MIT (see [LICENSE](../../LICENSE)). "Plex" is a trademark of Plex, Inc.; the demo has no',
  'connection to Plex, Inc. or to the films\' rights holders.', '');
out.push('## Films and shows', '');
out.push('| Title | Year | Status | Notes |', '| --- | --- | --- | --- |');
for (const m of [...(lib.movies || []), ...(lib.shows || [])]) {
  out.push(`| ${cell(m.title)} | ${m.year} | ${cell(m.licence)} | ${cell(m.licenceNote)} |`);
}
out.push('', 'Plot summaries are written for this demo. Cast and crew lists follow the films\' own credits.', '');
out.push('## Images', '');
out.push('| Used for | File | Author | Licence |', '| --- | --- | --- | --- |');
for (const [id, e] of Object.entries(lib.media || {})) {
  const file = (e.file || id).replace(/^File:/, '');
  out.push(`| ${cell((uses[id] || ['(unused)']).join('; '))} | ${link(file, e.page)}${e.note ? ` (${cell(e.note)})` : ''} | ${who(e.author)} | ${link(e.license, e.licenseUrl)} |`);
}
if (Object.keys(lib.videos || {}).length) {
  out.push('', '## Video', '', 'The demo plays these files straight from Wikimedia Commons. Backdrops and episode thumbnails marked', '"frame at …" above are video frames that Commons renders from them, under the same licence.', '');
  out.push('| Used for | File | Author | Licence |', '| --- | --- | --- | --- |');
  for (const [id, v] of Object.entries(lib.videos)) {
    const users = [
      ...(lib.movies || []).map((m) => [m.video, m.title]),
      ...(lib.movies || []).flatMap((m) => (m.extras || []).map((x) => [x.video, `${m.title}: ${x.subtype === 'trailer' ? 'trailer' : `"${x.title}"`}`])),
      ...(lib.shows || []).flatMap((s) => (s.seasons || []).flatMap((se) => (se.episodes || []).map((e) => [e.video, `${s.title}: "${e.title}"`]))),
    ].filter(([v]) => v === id).map(([, t]) => t);
    out.push(`| ${cell(users.join('; ') || id)} | ${link((v.file || id).replace(/^File:/, ''), v.page)} | ${who(v.author)} | ${link(v.license, v.licenseUrl)} |`);
  }
}
out.push('');
process.stdout.write(out.join('\n'));
