#!/usr/bin/env python3
"""Extracts the Phosphor icons the app uses into js/icons.js (only these, as element data).

    make-icons-js.py <path to an unpacked @phosphor-icons/core package>
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

# app name -> (weight, phosphor file name)
USED = {
    'play': ('fill', 'play-fill'),
    'restart': ('regular', 'arrow-counter-clockwise'),
    'trailer': ('regular', 'film-slate'),
    'shuffle': ('regular', 'shuffle'),
    'check': ('regular', 'check-circle'),
    'watched': ('fill', 'check-circle-fill'),
    'season': ('regular', 'list-checks'),
    'tracks': ('regular', 'subtitles'),
    'versions': ('regular', 'stack'),
    'show': ('regular', 'television-simple'),
}

pkg = Path(sys.argv[1])
version = json.loads((pkg / 'package.json').read_text())['version']
licence = (pkg / 'LICENSE').read_text().strip().splitlines()
icons = {}
for name, (weight, file) in USED.items():
    root = ET.parse(pkg / 'assets' / weight / f'{file}.svg').getroot()
    parts = []
    for el in root:
        tag = el.tag.split('}')[-1]
        parts.append([tag, {k: v for k, v in el.attrib.items()}])
    icons[name] = parts

header = '\n'.join('// ' + line if line else '//' for line in licence)
out = f"""// Generated by tools/make-icons-js.py from @phosphor-icons/core {version} (https://phosphoricons.com).
// Do not edit by hand. Phosphor Icons licence:
{header}
'use strict';

window.PL = window.PL || {{}};
PL.ICONS = {json.dumps(icons, separators=(',', ':'))};
"""
Path(__file__).resolve().parent.parent.joinpath('js', 'icons.js').write_text(out)
print('wrote js/icons.js with', len(icons), 'icons')
